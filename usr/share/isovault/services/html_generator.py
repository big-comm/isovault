"""
Builds the public index pages published to the bucket.

The page skeleton, CSS and JS live in templates/; this module only renders
the dynamic parts. Every value coming from the bucket is HTML-escaped.
"""

import locale
import os
from datetime import datetime, timezone
from html import escape
from string import Template
from typing import Callable, Dict, List, Optional

from config import DISTRO_FOLDERS, ROOT_FOLDER, TEMPLATES_DIR
from utils.helpers import extract_md5, pair_iso_with_md5
from utils.i18n import _

# Main page shows the root first, then the desktop folders
_MAIN_PAGE_ORDER = (ROOT_FOLDER,) + tuple(f for f in DISTRO_FOLDERS if f != ROOT_FOLDER)

# (CSS class, Lucide icon) per folder
_FOLDER_STYLE = {
    ROOT_FOLDER: ("root", "house"),
    "Gnome": ("gnome", "layout-grid"),
    "Cinnamon": ("cinnamon", "layers"),
    "XFCE": ("xfce", "monitor"),
}


def _read_template(name: str) -> str:
    with open(os.path.join(TEMPLATES_DIR, name), encoding="utf-8") as f:
        return f.read()


def _page_language() -> str:
    """BCP 47 tag of the UI language, e.g. "pt-BR" (the page text is translated)."""
    lang = locale.getlocale(locale.LC_MESSAGES)[0] or "en"
    return lang.replace("_", "-")


class HTMLGenerator:
    """Renders index.html pages for the whole bucket and for each folder"""

    def __init__(self, public_url: Callable[[str], str], lang: Optional[str] = None):
        """
        Args:
            public_url: Function that maps an S3 key to its public URL
            lang: Value of <html lang>; defaults to the current UI language
        """
        self.public_url = public_url
        self.lang = lang or _page_language()
        self._page = Template(_read_template("page.html"))
        self._style = _read_template("index.css")
        self._script = _read_template("index.js")

    def generate_main_index(
        self,
        files: List[Dict],
        md5_hashes: Dict[str, str],
        updated_at: Optional[datetime] = None,
    ) -> str:
        """
        Page listing the ISOs of every folder.

        Args:
            files: Files from S3Service.list_files()
            md5_hashes: Checksum file key -> MD5 read from that file
            updated_at: Timestamp shown on the page (default: now, UTC)
        """
        updated_at = updated_at or datetime.now(timezone.utc)

        sections = []
        total_isos = 0
        for folder in _MAIN_PAGE_ORDER:
            pairs = pair_iso_with_md5([f for f in files if f["folder"] == folder])
            if pairs:
                total_isos += len(pairs)
                sections.append(self._render_section(folder, pairs, md5_hashes, show_count=True))

        content = self._render_stats(total_isos, updated_at) + self._render_search()
        content += "".join(sections) if sections else self._render_empty(_("No ISO files available yet"))

        return self._render_page(_("BigCommunity ISO Repository"), content)

    def generate_folder_index(self, folder: str, files: List[Dict], md5_hashes: Dict[str, str]) -> str:
        """Page listing the ISOs of a single folder."""
        pairs = pair_iso_with_md5(files)

        content = f"""
        <div class="breadcrumb">
            <a href="../">{escape(_("All Folders"))}</a>
            <span>/</span>
            <strong>{escape(folder)}</strong>
        </div>
"""
        if pairs:
            content += self._render_section(folder, pairs, md5_hashes, show_count=False)
        else:
            content += self._render_empty(_("No files in this folder"))

        title = _("{folder_name} - BigCommunity ISO Repository").format(folder_name=folder)
        return self._render_page(title, content)

    # Rendering helpers

    def _render_page(self, title: str, content: str) -> str:
        return self._page.substitute(
            lang=escape(self.lang),
            title=escape(title),
            style=self._style,
            script=self._script,
            nav_home=escape(_("Home")),
            nav_download=escape(_("Download")),
            hero_text=escape(_("Direct download of BigCommunity ISO images with integrity verification.")),
            footer_text=escape(_("Generated by ISOVault")),
            toast_text=escape(_("MD5 copied!")),
            content=content,
        )

    def _render_stats(self, total_isos: int, updated_at: datetime) -> str:
        updated = updated_at.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        return f"""
        <div class="stats-bar">
            <div class="stat">
                <i data-lucide="disc-3"></i>
                <span><strong>{total_isos}</strong> {escape(_("ISO files available"))}</span>
            </div>
            <div class="stat-divider"></div>
            <div class="stat">
                <i data-lucide="clock"></i>
                <span>{escape(_("Updated"))}: {updated}</span>
            </div>
        </div>
"""

    def _render_search(self) -> str:
        return f"""
        <div class="search-wrapper">
            <i data-lucide="search"></i>
            <input type="text" class="search-input" id="searchInput" placeholder="{escape(_("Search ISOs..."))}">
        </div>
"""

    def _render_empty(self, message: str) -> str:
        return f"""
        <div class="empty-state">
            <i data-lucide="inbox"></i>
            <p>{escape(message)}</p>
        </div>
"""

    def _render_section(self, folder: str, pairs: List, md5_hashes: Dict[str, str], show_count: bool) -> str:
        css_class, icon = _FOLDER_STYLE.get(folder, _FOLDER_STYLE[ROOT_FOLDER])
        count = f'<span class="de-count">{len(pairs)} {escape(_("images"))}</span>' if show_count else ""
        cards = "".join(self._render_card(iso, md5_file, md5_hashes) for iso, md5_file in pairs)
        return f"""
        <div class="de-section">
            <div class="de-header">
                <div class="de-badge {css_class}">
                    <i data-lucide="{icon}"></i>
                </div>
                <div class="de-info">
                    <h2>{escape(folder)}</h2>
                    {count}
                </div>
            </div>
            <div class="file-grid">{cards}
            </div>
        </div>
"""

    def _render_card(self, iso: Dict, md5_file: Optional[Dict], md5_hashes: Dict[str, str]) -> str:
        name = escape(iso["name"])
        md5_hash = self._md5_for(md5_file, md5_hashes)

        md5_html = ""
        if md5_hash:  # always 32 lowercase hex chars, safe as-is
            md5_html = f"""
                    <div class="md5-section">
                        <div class="md5-label">{escape(_("MD5 Checksum"))}</div>
                        <div class="md5-row">
                            <span class="md5-hash">{md5_hash}</span>
                            <button class="md5-copy-btn" type="button" data-md5="{md5_hash}" title="{escape(_("Copy"))}">
                                <i data-lucide="copy"></i>
                            </button>
                        </div>
                    </div>"""

        return f"""
                <div class="file-card" data-filename="{name}">
                    <div class="file-card-header">
                        <div class="file-icon"><i data-lucide="disc-3"></i></div>
                        <div class="file-name">{name}</div>
                    </div>
                    <div class="file-meta">
                        <span class="file-meta-item size"><i data-lucide="hard-drive"></i>{escape(iso["size_formatted"])}</span>
                        <span class="file-meta-item date"><i data-lucide="calendar"></i>{iso["modified"].strftime("%Y-%m-%d")}</span>
                    </div>{md5_html}
                    <a class="download-btn" href="{escape(self.public_url(iso["key"]))}" target="_blank" rel="noopener">
                        <i data-lucide="download"></i>
                        {escape(_("Download ISO"))}
                    </a>
                </div>"""

    @staticmethod
    def _md5_for(md5_file: Optional[Dict], md5_hashes: Dict[str, str]) -> Optional[str]:
        """Validated hash read from the checksum file (None if missing or invalid)."""
        if not md5_file:
            return None
        return extract_md5(md5_hashes.get(md5_file["key"], ""))
